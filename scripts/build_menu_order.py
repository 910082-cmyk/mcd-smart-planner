"""
按麦当劳官方菜单顺序重构 seed-data.json。

数据来源：MCP query-meals(storeCode=3390081) 返回的 categories 数组。
该数组的顺序即为麦当劳中国现行菜单的官方顺序，本脚本将其固化为 menuOrder，
同时生成全局去重后的有序餐品列表（保留首次出现的分类归属）。

用法：python scripts/build_menu_order.py
"""
import json, io, os

BASE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data', 'seed-data.json')

# 官方菜单分类顺序（与 query-meals 返回的 categories 顺序严格一致）
OFFICIAL = [
    ("人气热卖", ["9900016076","9900016075","9900016073","9900016077","9900016311","9900004064","521950"]),
    ("精选单人餐", ["9900015856","9900015516","9900015527","9900004064","9900004236","9900010110","9900006957"]),
    ("鸡肉汉堡/卷", ["9900016075","9900016073","521953","521952","9900016310","9900016309","9900000891","9900000890","9900005462","9900005456","9900005453","1440","1406","1450","9900008746"]),
    ("小食拼盘/多人餐", ["9900016076","9900015726","9900006332","9900015730","9900011056","9900005321"]),
    ("蘸酱炸鸡", ["9900016078","9900016096","9900015729","521966","521799","521797"]),
    ("随心配 1+1", ["9900013304","9900015568"]),
    ("大堡口福 单人餐", ["9900015602"]),
    ("巨无霸 牛鱼肉堡", ["9900000888","9900000886","9900000885","9900000893","9900005411","9900005466","9900005468","9900005413","9900005460","9900005464","9900005449","521886","521887","1100","9900003586","1600","4648","1106","1120","521316","9900008747"]),
    ("安格斯MAX 厚牛堡", ["9900000881","9900000882","9900005428","9900005430","511781","511782"]),
    ("炸鸡", ["521966","521797","521799","9900005451","9900004835","1700","520445","1401","521156","9900005432"]),
    ("小食甜品/其他", ["521986","9900016082","521950","521951","521914","521917","521836","4810","514782","4437","6102","521750","9900008754","9900008745","515837","9900008752"]),
    ("开心乐园", ["9900016057","9900016058","9900016056","9900005439","9900016055","506189"]),
    ("麦咖啡", ["507411","507409","521548","510479","507387","514851","520689","514850","507394","510488"]),
    ("500 大卡套餐", ["9900011128","9900011121","9900011126","9900011123","9900009245","9900009242"]),
    ("饮品", ["521817","9900008751","3010","515520","2430","515280","3755","6362","3757","520689","3505"]),
]

def main():
    p = os.path.normpath(BASE)
    with io.open(p, encoding='utf-8') as f:
        d = json.load(f)
    menu = d['menu']
    missing = []
    order, seen, global_list = [], set(), []

    for name, codes in OFFICIAL:
        valid = []
        for c in codes:
            if c not in menu:
                missing.append((name, c)); continue
            valid.append(c)
            if c not in seen:
                seen.add(c); global_list.append(c)
        order.append({"name": name, "codes": valid})

    d['menuOrder'] = order
    d['menuGlobalOrder'] = global_list
    d['_meta']['menuOrderSource'] = 'MCP query-meals categories 原始返回顺序'

    with io.open(p, 'w', encoding='utf-8') as f:
        json.dump(d, f, ensure_ascii=False, indent=1)

    print('官方分类数：%d' % len(order))
    for it in order:
        print('  %-16s %d 项' % (it['name'], len(it['codes'])))
    print('全局去重餐品：%d 项（菜单共 %d）' % (len(global_list), len(menu)))
    if missing:
        print('警告：以下 code 在 menu 中不存在 -> %s' % missing)
    else:
        print('所有 code 校验通过，无缺失')

if __name__ == '__main__':
    main()